#!/usr/bin/env python
"""Audit the transcripts of every extracted session.

Works on the label files alone, so it can run before any video has been
preprocessed. Writes a Markdown report and a per-clip table.

Usage:
    python scripts/audit_labels.py --raw data/raw --report docs/label_audit.md
"""

import argparse
import csv
import glob
import os
import sys
from collections import Counter

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from avsr.data import manifest  # noqa: E402
from avsr.data.manifest import FilterConfig  # noqa: E402
from avsr.data.recurrence import BURST, LOOP, SENTENCE, find_recurrent, sentence_statistics  # noqa: E402
from avsr.text.labels import parse_label_file  # noqa: E402
from avsr.text.normalize import normalize_text  # noqa: E402

REASONS = [
    ("bad_label_file", "Label file missing or malformed"),
    ("empty_text", "No words left after normalisation"),
    ("hallucinated_phrase", "Known invented phrase (subtitle credit, sign-off)"),
    (LOOP, "A word or short phrase looping inside the transcript"),
    (BURST, "Same transcript as a neighbouring clip"),
    (SENTENCE, "Sentence that occurs mostly in bursts, met outside one"),
    ("squeezed_words", "Words too short to have been spoken"),
    ("low_confidence", "Low recogniser confidence"),
    ("speaking_rate", "Too many or too few characters per second"),
]


def load_sessions(raw_root):
    """Labels of every session in clip order: (clip_id, utterance or None, text)."""
    sessions = {}
    for session in sorted(os.listdir(raw_root)):
        folder = os.path.join(raw_root, session)
        if not os.path.isdir(folder) or session.startswith("."):
            continue
        clips = []
        for path in sorted(glob.glob(os.path.join(folder, "*.txt"))):
            clip_id = os.path.splitext(os.path.basename(path))[0]
            try:
                utt = parse_label_file(path)
                clips.append((clip_id, utt, normalize_text(utt.text)))
            except (OSError, ValueError):
                clips.append((clip_id, None, ""))
        if clips:
            sessions[session] = clips
    return sessions


def judge_label(utt, text, recurrent_reason, cfg):
    """Label verdict, plus a speaking-rate check that needs no video.

    The clip length is not known here; the end of the last word stands in
    for it.
    """
    reason = manifest.judge_label(utt, text, recurrent_reason, cfg)
    if reason:
        return reason
    rate = len(text.replace(" ", "")) / max(utt.speech_end, 1e-3)
    if not cfg.min_chars_per_sec <= rate <= cfg.max_chars_per_sec:
        return "speaking_rate"
    return None


def percent(part, whole):
    return f"{100 * part / whole:.1f} %" if whole else "—"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--raw", default="data/raw")
    parser.add_argument("--report", default="docs/label_audit.md")
    parser.add_argument("--table", default="data/label_audit.tsv")
    parser.add_argument("--top", type=int, default=40, help="Recurrent sentences to list")
    args = parser.parse_args()

    cfg = FilterConfig()
    sessions = load_sessions(args.raw)
    if not sessions:
        sys.exit(f"No sessions with label files under {args.raw}")
    recurrent = find_recurrent(
        {s: [(clip_id, text) for clip_id, _, text in clips] for s, clips in sessions.items()}, cfg.recurrence
    )

    rows, per_session, totals = [], {}, Counter()
    seconds_all = seconds_kept = 0.0
    letters = Counter()
    for session, clips in sessions.items():
        counts = Counter()
        for clip_id, utt, text in clips:
            reason = judge_label(utt, text, recurrent.get((session, clip_id)), cfg)
            counts[reason or "kept"] += 1
            duration = utt.speech_end if utt else 0.0
            seconds_all += duration
            seconds_kept += duration if reason is None else 0.0
            if utt:
                letters.update(c for c in utt.text if c in "Iİıi")
            rows.append(
                {
                    "session": session,
                    "clip_id": clip_id,
                    "verdict": reason or "kept",
                    "seconds": f"{duration:.2f}",
                    "mean_conf": f"{utt.mean_conf:.3f}" if utt else "",
                    "text": text,
                }
            )
        per_session[session] = counts
        totals.update(counts)

    os.makedirs(os.path.dirname(os.path.abspath(args.table)), exist_ok=True)
    with open(args.table, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]), delimiter="\t")
        writer.writeheader()
        writer.writerows(rows)

    total = sum(totals.values())
    out = ["# Label audit", ""]
    out += [
        f"Generated by `scripts/audit_labels.py` from the label files of {len(sessions)} sessions. "
        "It uses the transcripts only, so clips are counted whether or not a face can be found in them.",
        "",
        "## Overall",
        "",
        "| | Clips | Share | Hours |",
        "|---|---|---|---|",
        f"| All labelled clips | {total} | 100 % | {seconds_all / 3600:.1f} |",
        f"| Kept | {totals['kept']} | {percent(totals['kept'], total)} | {seconds_kept / 3600:.1f} |",
        f"| Rejected | {total - totals['kept']} | {percent(total - totals['kept'], total)} | "
        f"{(seconds_all - seconds_kept) / 3600:.1f} |",
        "",
        "Hours are measured to the end of the last word of each transcript. A clip is counted "
        "under the first check it fails, in the order of the table below, so the rows do not overlap.",
        "",
        "## Reasons for rejection",
        "",
        "| Check | Meaning | Clips | Share |",
        "|---|---|---|---|",
    ]
    for key, meaning in REASONS:
        out.append(f"| `{key}` | {meaning} | {totals[key]} | {percent(totals[key], total)} |")
    recurrent_total = totals[BURST] + totals[SENTENCE] + totals[LOOP] + totals["hallucinated_phrase"]
    out += [
        "",
        f"Recurrent or invented transcripts (the first four content checks together): "
        f"**{recurrent_total} clips, {percent(recurrent_total, total)}**.",
        "",
        "## By session",
        "",
        "| Session | Clips | Kept | Recurrent or invented | Low confidence | Other |",
        "|---|---|---|---|---|---|",
    ]
    for session, counts in per_session.items():
        n = sum(counts.values())
        rec = counts[BURST] + counts[SENTENCE] + counts[LOOP] + counts["hallucinated_phrase"]
        other = n - counts["kept"] - rec - counts["low_confidence"]
        out.append(
            f"| {session} | {n} | {percent(counts['kept'], n)} | {percent(rec, n)} | "
            f"{percent(counts['low_confidence'], n)} | {percent(other, n)} |"
        )

    stats = sentence_statistics(
        {s: [(clip_id, text) for clip_id, _, text in clips] for s, clips in sessions.items()}, recurrent
    )
    rejected = [r for r in stats if r["flagged"]]
    kept = [r for r in stats if not r["flagged"]]
    out += [
        "",
        "## Most frequent rejected sentences",
        "",
        "| Occurrences | Sessions | Rejected | Sentence |",
        "|---|---|---|---|",
    ]
    for r in rejected[: args.top]:
        text = r["text"] if len(r["text"]) <= 70 else r["text"][:67] + "..."
        out.append(f"| {r['count']} | {r['sessions']} | {r['flagged']} | {text} |")
    out += [
        "",
        "## Most frequent sentences that are kept",
        "",
        "These repeat without bunching together, which is how genuine formulae behave. "
        "Anything here that looks invented should be added to `HALLUCINATED_PHRASES`.",
        "",
        "| Occurrences | Sessions | Sentence |",
        "|---|---|---|",
    ]
    for r in kept[: args.top]:
        text = r["text"] if len(r["text"]) <= 70 else r["text"][:67] + "..."
        out.append(f"| {r['count']} | {r['sessions']} | {text} |")
    out += [
        "",
        "## Dotted and dotless I",
        "",
        "| Letter in the raw transcripts | Count |",
        "|---|---|",
        f"| `I` | {letters['I']} |",
        f"| `İ` | {letters['İ']} |",
        f"| `ı` | {letters['ı']} |",
        f"| `i` | {letters['i']} |",
        "",
        "In correctly cased Turkish text `İ` is about as frequent as `I`. The imbalance shows that "
        "the transcripts were upper-cased without Turkish rules, which turned both letters into `I`.",
        "",
        f"Per-clip verdicts: `{args.table}`.",
        "",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(args.report)), exist_ok=True)
    with open(args.report, "w", encoding="utf-8") as f:
        f.write("\n".join(out))
    print("\n".join(out[:32]))
    print(f"...\nreport: {args.report}\ntable : {args.table}")


if __name__ == "__main__":
    main()
